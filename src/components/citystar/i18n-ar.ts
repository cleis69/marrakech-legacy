/**
 * Accord du nom avec le nombre en arabe : 1 → singulier, 2 → duel, 3 à 10 → pluriel,
 * 11 et plus (et 0) → singulier à l'accusatif (« 14 فيلا », « 12 شهرًا »).
 */
const compter = (n: number, un: string, deux: string, pluriel: string, singulier: string) =>
  n === 1 ? un : n === 2 ? deux : n >= 3 && n <= 10 ? `${n} ${pluriel}` : `${n} ${singulier}`;

