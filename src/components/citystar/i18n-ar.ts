/** « dans n mois » : بعد شهر واحد، بعد شهرين، بعد 5 أشهر، بعد 12 شهرًا. */
const baadAchhor = (n: number) =>
  n === 0
    ? "هذا الشهر"
    : n === 1
      ? "بعد شهر واحد"
      : n === 2
        ? "بعد شهرين"
        : n <= 10
          ? `بعد ${n} أشهر`
          : `بعد ${n} شهرًا`;

